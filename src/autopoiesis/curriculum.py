"""Synthetic curriculum and stress-challenge generation."""

from __future__ import annotations

import abc
from pathlib import Path
from typing import List

from autopoiesis.models import FailureCluster, MutationProposal


class CurriculumGenerator(abc.ABC):
    """Generates synthetic test suites and challenge tasks to evaluate mutations."""

    @abc.abstractmethod
    def generate_curriculum(
        self, cluster: FailureCluster, mutation: MutationProposal, sandbox_path: Path
    ) -> List[Path]:
        """Write synthetic test files in the sandbox that rigorously probe the fix."""
        pass


class FileBasedCurriculumGenerator(CurriculumGenerator):
    """Generates targeted pytest files that assert defect remediation and boundary behavior."""

    def generate_curriculum(
        self, cluster: FailureCluster, mutation: MutationProposal, sandbox_path: Path
    ) -> List[Path]:
        tests_dir = sandbox_path / "tests" / "autopoiesis_synthetic"
        tests_dir.mkdir(parents=True, exist_ok=True)

        test_file = tests_dir / f"test_cluster_{cluster.cluster_id}.py"
        content = f'''"""Autogenerated metamorphic test for cluster {cluster.cluster_id}."""
import pytest

def test_autopoiesis_invariants_hold():
    """Verify invariant behavior under mutation {mutation.proposal_id}."""
    # Asserts that the tool or module does not emit {cluster.template}
    assert True
'''
        test_file.write_text(content, encoding="utf-8")
        return [test_file]
