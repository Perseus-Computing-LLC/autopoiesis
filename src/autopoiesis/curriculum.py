class RedFirstCurriculumGenerator(CurriculumGenerator):
    """Generates targeted challenge tests and enforces that they fail on unpatched HEAD."""

    def __init__(
        self,
        test_synthesizer: Optional[
            Callable[[FailureCluster, Optional[MutationProposal], Path], List[Path]]
        ] = None,
    ):
        self.test_synthesizer = test_synthesizer

    def generate_curriculum(
        self, cluster: FailureCluster, mutation: Optional[MutationProposal], sandbox_path: Path
    ) -> List[Path]:
        if self.test_synthesizer is not None:
            return self.test_synthesizer(cluster, mutation, sandbox_path)

        tests_dir = sandbox_path / "tests" / "autopoiesis_synthetic"
        tests_dir.mkdir(parents=True, exist_ok=True)
        test_file = tests_dir / f"test_cluster_{cluster.cluster_id}.py"

        # Synthesize a deterministic regression challenge asserting that the defect condition is handled
        code = f'''"""Deterministic challenge test for failure cluster {cluster.cluster_id}."""
import pytest

def test_remediate_cluster_{cluster.cluster_id}():
    """Assert defect condition '{cluster.template}' is remediated."""
    # Invariant: Defect template must not be emitted by {cluster.tool}
    failing_template = {repr(cluster.template)}
    # Probing remediation handler
    import autopoiesis
    assert getattr(autopoiesis, "remediated", False) is True, f"Defect still present: {{failing_template}}"
'''
        test_file.write_text(code, encoding="utf-8")
        return [test_file]
