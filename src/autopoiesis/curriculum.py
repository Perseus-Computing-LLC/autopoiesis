"""Synthetic curriculum and stress-challenge generation."""

from __future__ import annotations

import abc
import os
import subprocess
import sys
from pathlib import Path
from typing import Callable, List, Optional

from autopoiesis.models import FailureCluster, MutationProposal


class CurriculumGenerator(abc.ABC):
    """Generates synthetic test suites and challenge tasks to evaluate mutations."""

    @abc.abstractmethod
    def generate_curriculum(
        self, cluster: FailureCluster, mutation: Optional[MutationProposal], sandbox_path: Path
    ) -> List[Path]:
        """Write synthetic test files in the sandbox that probe the fix."""
        pass

    def verify_red_on_head(
        self,
        test_paths: List[Path],
        head_path: Path,
        pythonpath: Optional[str] = None,
        timeout_seconds: int = 60,
    ) -> bool:
        """Verify that synthetic challenge tests FAIL (RED) on unpatched HEAD.

        Returns True if at least one challenge test fails on unpatched HEAD (RED-first satisfied).
        Returns False if all challenge tests PASS on unpatched HEAD (violating RED-first invariant).
        """
        if not test_paths:
            return False

        sub_env = os.environ.copy()
        pp = str(head_path)
        if pythonpath:
            pp = f"{pp}:{pythonpath}"
        existing_pp = sub_env.get("PYTHONPATH", "")
        sub_env["PYTHONPATH"] = f"{pp}:{existing_pp}" if existing_pp else pp

        any_failed = False
        for tp in test_paths:
            cmd = [sys.executable, "-m", "pytest", "-q", str(tp)]
            try:
                res = subprocess.run(
                    cmd,
                    cwd=str(head_path),
                    env=sub_env,
                    capture_output=True,
                    text=True,
                    timeout=timeout_seconds,
                )
                if res.returncode != 0:
                    any_failed = True
                    break
            except Exception:
                any_failed = True
                break

        return any_failed


class FileBasedCurriculumGenerator(CurriculumGenerator):
    """Generates targeted pytest files that assert defect remediation and boundary behavior."""

    def generate_curriculum(
        self, cluster: FailureCluster, mutation: Optional[MutationProposal], sandbox_path: Path
    ) -> List[Path]:
        tests_dir = sandbox_path / "tests" / "autopoiesis_synthetic"
        tests_dir.mkdir(parents=True, exist_ok=True)

        prop_id = mutation.proposal_id if mutation else "none"
